"""Writes generated/extracted.rs: Rust constants with a provenance line above each value.

Every value carries where it came from, so the generated table documents itself:
    // SRC: regulation.bin EquipParamWeapon[2000000].attackBasePhysics = 110
    pub const ...: f32 = 110.0;
Values you could not extract go in with `// ESTIMATE: <why>` instead.
"""
from pathlib import Path


def f32(x):
    s = repr(float(x))
    return s if ("." in s or "e" in s or "inf" in s or "nan" in s) else s + ".0"


class Value:
    def __init__(self, value, src=None, estimate=None):
        assert (src is None) != (estimate is None), "give exactly one of src= or estimate="
        self.value, self.src, self.estimate = value, src, estimate

    def comment(self):
        return f"// SRC: {self.src}" if self.src else f"// ESTIMATE: {self.estimate}"


def window(w):
    if w is None:
        return "Window::NEVER"
    return f"Window {{ from: {f32(w[0])}, to: {f32(w[1])} }}"


def write(path: Path, source: str, scalars: dict, actions: list):
    """scalars: NAME -> Value(float). actions: list of dicts with ActionDef fields plus 'src'."""
    out = [
        "// GENERATED by tools/extract.py from the installed game. Do not edit by hand: rerun the tool.",
        "// Plain // comments only: this file is include!d.",
        "",
        "use crate::actions::{ActionDef, Window};",
        "",
        f"pub const SOURCE: &str = {source!r};".replace("'", '"'),
        "",
    ]
    for name, v in scalars.items():
        out += [v.comment(), f"pub const {name}: f32 = {f32(v.value)};"]
    out += ["", "pub const ACTIONS: &[ActionDef] = &["]
    for a in actions:
        out.append(f"    // SRC: {a['src']}")
        out.append("    ActionDef {")
        out.append(f"        name: \"{a['name']}\",")
        out.append(f"        len: {f32(a['len'])},")
        out.append(f"        hit: {window(a.get('hit'))},")
        out.append(f"        iframes: {window(a.get('iframes'))},")
        for k in ("input_from", "cancel_into_attack", "cancel_into_dodge", "cancel_into_move",
                  "root_motion", "stamina", "damage", "reach"):
            out.append(f"        {k}: {f32(a[k])},")
        out.append(f"        next: \"{a.get('next', '')}\",")
        out.append("    },")
    out.append("];")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(scalars)} values, {len(actions)} actions)")
